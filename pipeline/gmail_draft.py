"""Create a Gmail DRAFT (never send) to the found contacts with the PDF attached.

The email body is generated by the Anthropic API: short, personalised, and
grounded only in the tailored resume + job posting (no fabricated claims).
"""
from __future__ import annotations

import base64
import mimetypes
import re
from email.message import EmailMessage
from pathlib import Path

import anthropic
from googleapiclient.discovery import build

from config import CONFIG
from pipeline.contacts import Contact
from pipeline.google_auth import get_credentials
from pipeline.resume import TailoredResume
from pipeline.scraper import JobPosting

EMAIL_SYSTEM = """You write short, sincere outreach emails from a job applicant \
to people at the hiring company. Constraints:
- 110-150 words, plain and direct, no buzzwords, no flattery padding.
- Only use facts present in the provided resume summary and job posting. Never \
invent metrics, experience or claims.
- One concrete reason the candidate fits, phrased honestly for an early-career hire.
- Do NOT lead with or foreground the candidate's undergraduate degree/classification as the \
pitch - it reads thin. Prefer real project work, the actual jobs held, and genuine motivation \
instead. The degree can be mentioned in passing (e.g. dating the MRes) but is never the reason \
given for fit.
- Say the candidate "is applying" / "is submitting an application" for the role - \
do NOT claim they have already applied.
- Mention the attached CV and the role title. Ask for a brief conversation or to \
be pointed to the right person.
- Do NOT add a sign-off or signature (it is appended automatically).
- Do NOT include a subject line. Return only the email body text."""


def _generate_email(job: JobPosting, resume: TailoredResume, contacts: list[Contact]) -> dict:
    client = anthropic.Anthropic(api_key=CONFIG.anthropic_api_key)
    recipients = "; ".join(f"{c.name} ({c.title})" for c in contacts) or "the hiring team"
    prompt = f"""Candidate: {CONFIG.applicant.name}
Recipients: {recipients}
Role: {job.title} at {job.company}
Job URL: {job.url}

Resume summary: {resume.summary}
Top skills: {", ".join(resume.skills[:12])}

Write the email."""
    msg = client.messages.create(
        model=CONFIG.anthropic_model,
        max_tokens=2000,
        system=EMAIL_SYSTEM,
        messages=[{"role": "user", "content": prompt}],
    )
    body = next((b.text for b in msg.content if b.type == "text"), "").strip()
    body = re.sub(r"^\s*SUBJECT:.*?\r?\n+", "", body, flags=re.IGNORECASE)
    subject = f"{job.title} - {CONFIG.applicant.name} - {job.company}"
    return {"subject": subject, "body": body}


def _build_mime(
    to_addrs: list[str], subject: str, body: str, pdf_path: str
) -> EmailMessage:
    message = EmailMessage()
    message["To"] = ", ".join(to_addrs) if to_addrs else CONFIG.applicant.email
    # From is left to Gmail (the authorised account). Replies go to the address
    # the candidate put on the CV.
    if CONFIG.applicant.email:
        message["Reply-To"] = CONFIG.applicant.email
    message["Subject"] = subject
    signature = f"\n\n--\n{CONFIG.applicant.name}\n{CONFIG.applicant.email}"
    if CONFIG.applicant.phone:
        signature += f"\n{CONFIG.applicant.phone}"
    if CONFIG.applicant.linkedin:
        signature += f"\n{CONFIG.applicant.linkedin}"
    message.set_content(body.rstrip() + signature)

    pdf_path = Path(pdf_path)
    ctype, _ = mimetypes.guess_type(str(pdf_path))
    maintype, subtype = (ctype or "application/pdf").split("/", 1)
    message.add_attachment(
        pdf_path.read_bytes(),
        maintype=maintype,
        subtype=subtype,
        filename=pdf_path.name,
    )
    return message


def create_draft(
    job: JobPosting,
    resume: TailoredResume,
    contacts: list[Contact],
    pdf_path: str,
) -> dict:
    """Create the draft. Returns {draft_id, subject, to, unresolved_contacts}."""
    email = _generate_email(job, resume, contacts)

    real = [c for c in contacts if c.email_is_real]
    unresolved = [c for c in contacts if not c.email_is_real]
    to_addrs = [c.email for c in real]

    subject = email.get("subject", job.title)
    body = email.get("body", "")
    if unresolved:
        names = ", ".join(f"{c.name} ({c.title})" for c in unresolved)
        body += (
            f"\n\n[DRAFT NOTE - not part of the email] No verified address was "
            f"found for: {names}. Add them manually before sending."
        )
    if not to_addrs:
        body += (
            "\n\n[DRAFT NOTE] No contacts were found for this company. Add "
            "recipients (recruiter / hiring manager) before sending, or use this "
            "text as a covering note in the online application."
        )

    mime = _build_mime(to_addrs, subject, body, pdf_path)
    raw = base64.urlsafe_b64encode(mime.as_bytes()).decode()

    service = build("gmail", "v1", credentials=get_credentials(), cache_discovery=False)
    existing_id = _find_existing_draft(service, subject)
    if existing_id:
        draft = (
            service.users()
            .drafts()
            .update(userId="me", id=existing_id, body={"message": {"raw": raw}})
            .execute()
        )
        action = "updated"
    else:
        draft = (
            service.users()
            .drafts()
            .create(userId="me", body={"message": {"raw": raw}})
            .execute()
        )
        action = "created"
    return {
        "draft_id": draft.get("id"),
        "action": action,
        "subject": subject,
        "to": to_addrs,
        "unresolved_contacts": [f"{c.name} <{c.title}>" for c in unresolved],
    }


def _find_existing_draft(service, subject: str) -> str | None:
    """Reuse a draft with the same subject so re-runs don't pile up duplicates.

    Uses only drafts.* calls - the gmail.compose scope cannot read messages.*.
    """
    want = subject.strip()
    try:
        resp = service.users().drafts().list(userId="me", maxResults=100).execute()
        for d in resp.get("drafts", []):
            draft = (
                service.users()
                .drafts()
                .get(userId="me", id=d["id"], format="metadata")
                .execute()
            )
            headers = {
                h["name"]: h["value"]
                for h in draft.get("message", {}).get("payload", {}).get("headers", [])
            }
            if headers.get("Subject", "").strip() == want:
                return d["id"]
    except Exception:  # noqa: BLE001
        pass
    return None
